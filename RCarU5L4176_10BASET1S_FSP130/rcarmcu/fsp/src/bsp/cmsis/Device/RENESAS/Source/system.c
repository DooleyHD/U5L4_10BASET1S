#if BSP_CFG_C_RUNTIME_INIT
 #if defined(__GNUC__)

static void bsp_gcc_runtime_init (void)
{
    /* Zero out BSS */
    memset(&__bss_start__, 0U, ((uint32_t) &__bss_end__ - (uint32_t) &__bss_start__));

    R_BSP_CheckChipStandByMode();
    if (BSP_CYCLICRUN_MODE != R_BSP_GetChipStandByMode())
    {
        /* Zero out gram bss */
        memset(&__gram_bss_start__, 0U, ((uint32_t) &__gram_bss_end__ - (uint32_t) &__gram_bss_start__));
    }

    /* Copy initialized RAM data from ROM to RAM */
    memcpy(&__data_start__, &__data_load_start__, ((uint32_t) &__data_end__ - (uint32_t) &__data_start__));

    /* Initialize static constructors */
    int32_t count = __init_array_end - __init_array_start;
    for (int32_t i = 0; i < count; i++)
    {
        __init_array_start[i]();
    }
}

 #elif defined(__ICCARM__)

static void bsp_iar_runtime_init (void)
{
    /* Zero out BSS */
    memset(&__ram_zero_initialized_block_start,
           0U,
           (uint32_t) &__ram_zero_initialized_block_end - (uint32_t) &__ram_zero_initialized_block_start);

    R_BSP_CheckChipStandByMode();
    if (BSP_CYCLICRUN_MODE != R_BSP_GetChipStandByMode())
    {
        /* Zero out gram bss */
        memset(&__gram_zero_initialized_block_start,
               0U,
               (uint32_t) &__gram_zero_initialized_block_end - (uint32_t) &__gram_zero_initialized_block_start);
    }

    /* Copy initialized RAM data from ROM to RAM */
    memcpy(&__ram_initialized_block_start,
           &__code_flash_ram_initialized_block_start,
           (uint32_t) &__ram_initialized_block_end - (uint32_t) &__ram_initialized_block_start);

    /* Initialize static constructors */
    void const * pibase = __section_begin("SHT$$PREINIT_ARRAY");
    void const * ilimit = __section_end("SHT$$INIT_ARRAY");
    __call_ctors(pibase, ilimit);
}

 #endif
#endif

